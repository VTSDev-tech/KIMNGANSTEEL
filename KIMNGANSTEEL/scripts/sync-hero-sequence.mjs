import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");
const defaultSource = "C:\\Users\\Art5\\Downloads\\herokimngan";
const sourceDir = process.env.HERO_SEQUENCE_SOURCE || defaultSource;
const publicDir = path.join(projectRoot, "public", "hero_sequence");
const manifestPath = path.join(projectRoot, "src", "components", "antra", "heroSequenceManifest.ts");

const numericSvgSort = (a, b) => Number.parseInt(a, 10) - Number.parseInt(b, 10);
const listSvgFrames = (dir) =>
  readdirSync(dir)
    .filter((file) => /^\d+\.svg$/i.test(file))
    .sort(numericSvgSort);

mkdirSync(publicDir, { recursive: true });

let frames = [];

if (existsSync(sourceDir)) {
  frames = listSvgFrames(sourceDir);
  for (const frame of frames) {
    copyFileSync(path.join(sourceDir, frame), path.join(publicDir, frame));
  }
} else if (existsSync(publicDir)) {
  frames = listSvgFrames(publicDir);
}

if (frames.length === 0) {
  throw new Error(`No numeric SVG frames found in ${sourceDir} or ${publicDir}`);
}

const urls = frames.map((frame) => `/hero_sequence/${frame}`);
const manifest = `// This file is generated by scripts/sync-hero-sequence.mjs.
// Do not edit manually. Add numeric SVG frames to the source folder and run npm run sync:hero-sequence.

export const heroSequenceFrames = ${JSON.stringify(urls, null, 2)} as const;
`;

writeFileSync(manifestPath, manifest, "utf8");
console.log(`Hero sequence synced: ${frames.length} frame(s).`);
